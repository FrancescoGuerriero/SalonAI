#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDir, "..");
const manifestPath = resolve(frontendRoot, "figma/aiibp.tokens.json");

const command = process.argv[2] || "check";
const remoteCommands = new Set(["pull", "push", "remote-check"]);

function fail(message) {
  throw new Error(message);
}

function round255(value) {
  return Math.max(0, Math.min(255, Math.round(Number(value) * 255)));
}

function hexByte(value) {
  return round255(value).toString(16).padStart(2, "0");
}

function colorToCss(value) {
  if (!value || typeof value !== "object") {
    fail("Figma color value is missing or invalid.");
  }
  const alpha = value.a === undefined ? 1 : Number(value.a);
  const hex = `#${hexByte(value.r)}${hexByte(value.g)}${hexByte(value.b)}`;
  if (alpha >= 0.999) {
    return hex;
  }
  return `rgba(${round255(value.r)}, ${round255(value.g)}, ${round255(value.b)}, ${Number(alpha.toFixed(4))})`;
}

function cssColorToFigma(value) {
  const text = String(value).trim().toLowerCase();
  const hex = text.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (hex) {
    const body = hex[1];
    const alpha = hex[2] ? parseInt(hex[2], 16) / 255 : 1;
    return {
      r: parseInt(body.slice(0, 2), 16) / 255,
      g: parseInt(body.slice(2, 4), 16) / 255,
      b: parseInt(body.slice(4, 6), 16) / 255,
      a: alpha,
    };
  }

  const rgba = text.match(
    /^rgba?\(\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)\s*(?:,\s*(\d+(?:\.\d+)?)\s*)?\)$/
  );
  if (rgba) {
    return {
      r: Number(rgba[1]) / 255,
      g: Number(rgba[2]) / 255,
      b: Number(rgba[3]) / 255,
      a: rgba[4] === undefined ? 1 : Number(rgba[4]),
    };
  }

  fail(`Unsupported CSS color "${value}". Use #RRGGBB, #RRGGBBAA, rgb(), or rgba().`);
}

async function loadManifest() {
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  validateManifest(manifest);
  return manifest;
}

function validateManifest(manifest) {
  if (manifest.schemaVersion !== 1) {
    fail(`Unsupported token manifest schemaVersion: ${manifest.schemaVersion}`);
  }
  if (!manifest.figmaFileKey) {
    fail("figmaFileKey is required.");
  }
  if (!Array.isArray(manifest.collections) || !Array.isArray(manifest.tokens)) {
    fail("collections and tokens arrays are required.");
  }

  const collectionNames = new Set();
  const collectionIds = new Set();
  for (const collection of manifest.collections) {
    if (!collection.name || !collection.figmaId || !collection.mode?.figmaId) {
      fail(`Collection metadata is incomplete for "${collection.name || "unknown"}".`);
    }
    if (collectionNames.has(collection.name) || collectionIds.has(collection.figmaId)) {
      fail(`Duplicate collection identity: ${collection.name}.`);
    }
    collectionNames.add(collection.name);
    collectionIds.add(collection.figmaId);
  }

  const tokenNames = new Set();
  const tokenIds = new Set();
  const cssVars = new Set();
  for (const token of manifest.tokens) {
    if (!collectionNames.has(token.collection)) {
      fail(`Token "${token.name}" references unknown collection "${token.collection}".`);
    }
    if (!token.figmaId || !token.name || !token.type || !token.cssVar) {
      fail(`Token metadata is incomplete for "${token.name || "unknown"}".`);
    }
    if (!/^--[a-z0-9-]+$/i.test(token.cssVar)) {
      fail(`Invalid CSS custom property "${token.cssVar}".`);
    }
    if (tokenNames.has(token.name) || tokenIds.has(token.figmaId) || cssVars.has(token.cssVar)) {
      fail(`Duplicate token identity detected for "${token.name}".`);
    }
    tokenNames.add(token.name);
    tokenIds.add(token.figmaId);
    cssVars.add(token.cssVar);
  }

  for (const token of manifest.tokens) {
    if (token.value && typeof token.value === "object" && "alias" in token.value) {
      if (!tokenNames.has(token.value.alias)) {
        fail(`Token "${token.name}" aliases missing token "${token.value.alias}".`);
      }
    }
  }
}

function cssValue(token, byName) {
  if (token.value && typeof token.value === "object" && "alias" in token.value) {
    const target = byName.get(token.value.alias);
    if (!target) fail(`Alias target "${token.value.alias}" is missing.`);
    return `var(${target.cssVar})`;
  }
  if (token.type === "FLOAT") {
    return `${token.value}${token.unit || ""}`;
  }
  return String(token.value);
}

function generateCss(manifest) {
  const byName = new Map(manifest.tokens.map((token) => [token.name, token]));
  const lines = [
    "/*",
    " * AUTO-GENERATED by frontend/scripts/figma-sync.mjs.",
    " * Source: frontend/figma/aiibp.tokens.json.",
    " * Do not edit this file by hand.",
    " */",
    "",
    ":root {",
  ];

  for (const collection of manifest.collections) {
    lines.push(`  /* ${collection.name} */`);
    for (const token of manifest.tokens.filter((item) => item.collection === collection.name)) {
      lines.push(`  ${token.cssVar}: ${cssValue(token, byName)};`);
    }
    lines.push("");
  }

  if (lines.at(-1) === "") lines.pop();
  lines.push("}", "");
  return lines.join("\n");
}

async function writeGeneratedCss(manifest) {
  const cssPath = resolve(frontendRoot, manifest.generatedCss);
  await writeFile(cssPath, generateCss(manifest), "utf8");
  return cssPath;
}

function requireToken() {
  const token = String(process.env.FIGMA_ACCESS_TOKEN || "").trim();
  if (!token) {
    fail(
      "FIGMA_ACCESS_TOKEN is required for remote synchronization. " +
        "Store it as a GitHub Actions secret; never commit it."
    );
  }
  return token;
}

async function figmaRequest(manifest, path, options = {}) {
  const token = requireToken();
  const response = await fetch(`https://api.figma.com/v1${path}`, {
    ...options,
    headers: {
      "Content-Type": "application/json",
      "X-Figma-Token": token,
      ...(options.headers || {}),
    },
  });
  const text = await response.text();
  let body = null;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    body = text;
  }

  if (!response.ok) {
    const detail =
      typeof body === "string"
        ? body
        : body?.message || body?.err || body?.error || JSON.stringify(body);
    if (response.status === 403) {
      fail(
        `Figma API returned 403: ${detail}. The Variables REST API requires an Enterprise ` +
          "workspace/full seat, file access, and file_variables:read/write scopes."
      );
    }
    fail(`Figma API ${response.status}: ${detail}`);
  }
  return body;
}

async function getRemoteVariables(manifest) {
  return figmaRequest(manifest, `/files/${manifest.figmaFileKey}/variables/local`);
}

function remoteIndex(remote) {
  const variables = Object.values(remote?.meta?.variables || {});
  const collections = Object.values(remote?.meta?.variableCollections || {});
  const collectionById = new Map(collections.map((collection) => [collection.id, collection]));
  const variableById = new Map(variables.map((variable) => [variable.id, variable]));
  const variableByQualifiedName = new Map(
    variables.map((variable) => {
      const collection = collectionById.get(variable.variableCollectionId);
      return [`${collection?.name || variable.variableCollectionId}::${variable.name}`, variable];
    })
  );
  return { variables, collections, collectionById, variableById, variableByQualifiedName };
}

function normalizeRemoteValue(token, raw, index) {
  if (raw && typeof raw === "object" && raw.type === "VARIABLE_ALIAS") {
    const target = index.variableById.get(raw.id);
    if (!target) fail(`Remote alias target ${raw.id} for "${token.name}" was not returned by Figma.`);
    return { alias: target.name };
  }
  if (token.type === "COLOR") return colorToCss(raw);
  if (token.type === "FLOAT") return Number(raw);
  return raw;
}

async function pull(manifest) {
  const remote = await getRemoteVariables(manifest);
  const index = remoteIndex(remote);
  const managedCollections = new Set(manifest.collections.map((collection) => collection.name));
  const managedNames = new Set(manifest.tokens.map((token) => `${token.collection}::${token.name}`));

  const unmanaged = index.variables.filter((variable) => {
    const collectionName = index.collectionById.get(variable.variableCollectionId)?.name;
    return managedCollections.has(collectionName) && !managedNames.has(`${collectionName}::${variable.name}`);
  });
  if (unmanaged.length > 0) {
    fail(
      "Figma contains unmanaged variables in synchronized collections: " +
        unmanaged
          .map((variable) => `${index.collectionById.get(variable.variableCollectionId)?.name}/${variable.name}`)
          .join(", ") +
        ". Add them deliberately to aiibp.tokens.json before automated pull can continue."
    );
  }

  for (const collection of manifest.collections) {
    const remoteCollection = index.collections.find((item) => item.name === collection.name);
    if (!remoteCollection) fail(`Figma collection "${collection.name}" is missing.`);
    collection.figmaId = remoteCollection.id;
    const remoteMode =
      remoteCollection.modes?.find((mode) => mode.name === collection.mode.name) ||
      remoteCollection.modes?.[0];
    if (!remoteMode) fail(`Figma collection "${collection.name}" has no mode.`);
    collection.mode.figmaId = remoteMode.modeId;
    collection.mode.name = remoteMode.name;
  }

  for (const token of manifest.tokens) {
    const variable =
      index.variableById.get(token.figmaId) ||
      index.variableByQualifiedName.get(`${token.collection}::${token.name}`);
    if (!variable) fail(`Figma variable "${token.collection}/${token.name}" is missing.`);
    if (variable.resolvedType !== token.type) {
      fail(
        `Type drift for "${token.name}": manifest=${token.type}, Figma=${variable.resolvedType}. ` +
          "Type changes require an explicit migration."
      );
    }
    token.figmaId = variable.id;
    token.scopes = Array.isArray(variable.scopes) ? variable.scopes : token.scopes;
    const collection = manifest.collections.find((item) => item.name === token.collection);
    const raw = variable.valuesByMode?.[collection.mode.figmaId];
    if (raw === undefined) fail(`Mode value missing for "${token.name}".`);
    token.value = normalizeRemoteValue(token, raw, index);
  }

  validateManifest(manifest);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  await writeGeneratedCss(manifest);
}

function toRemoteValue(token, byName) {
  if (token.value && typeof token.value === "object" && "alias" in token.value) {
    const target = byName.get(token.value.alias);
    if (!target) fail(`Alias target "${token.value.alias}" is missing.`);
    return { type: "VARIABLE_ALIAS", id: target.figmaId };
  }
  if (token.type === "COLOR") return cssColorToFigma(token.value);
  if (token.type === "FLOAT") return Number(token.value);
  return token.value;
}

async function push(manifest) {
  const byName = new Map(manifest.tokens.map((token) => [token.name, token]));
  const collectionByName = new Map(manifest.collections.map((collection) => [collection.name, collection]));

  const payload = {
    variables: manifest.tokens.map((token) => ({
      action: "UPDATE",
      id: token.figmaId,
      scopes: token.scopes,
      codeSyntax: { WEB: `var(${token.cssVar})` },
    })),
    variableModeValues: manifest.tokens.map((token) => ({
      variableId: token.figmaId,
      modeId: collectionByName.get(token.collection).mode.figmaId,
      value: toRemoteValue(token, byName),
    })),
  };

  await figmaRequest(manifest, `/files/${manifest.figmaFileKey}/variables`, {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

async function remoteCheck(manifest) {
  const remote = await getRemoteVariables(manifest);
  const index = remoteIndex(remote);
  const diffs = [];
  const remoteCollectionByName = new Map(index.collections.map((collection) => [collection.name, collection]));

  for (const collection of manifest.collections) {
    const remoteCollection = remoteCollectionByName.get(collection.name);
    if (!remoteCollection) {
      diffs.push(`${collection.name}: collection missing in Figma`);
      continue;
    }

    if (remoteCollection.id !== collection.figmaId) {
      diffs.push(`${collection.name}: collection id code=${collection.figmaId} figma=${remoteCollection.id}`);
    }

    const remoteMode =
      remoteCollection.modes?.find((mode) => mode.name === collection.mode.name) || null;
    if (!remoteMode) {
      diffs.push(`${collection.name}: mode "${collection.mode.name}" missing in Figma`);
      continue;
    }
    if (remoteMode.modeId !== collection.mode.figmaId) {
      diffs.push(
        `${collection.name}: mode id code=${collection.mode.figmaId} figma=${remoteMode.modeId}`
      );
    }
  }

  const managedCollections = new Set(manifest.collections.map((collection) => collection.name));
  const managedNames = new Set(manifest.tokens.map((token) => `${token.collection}::${token.name}`));
  for (const variable of index.variables) {
    const collectionName = index.collectionById.get(variable.variableCollectionId)?.name;
    if (managedCollections.has(collectionName) && !managedNames.has(`${collectionName}::${variable.name}`)) {
      diffs.push(`${collectionName}/${variable.name}: unmanaged variable exists in synchronized collection`);
    }
  }

  for (const token of manifest.tokens) {
    const remoteCollection = remoteCollectionByName.get(token.collection);
    const remoteMode =
      remoteCollection?.modes?.find(
        (mode) => mode.name === manifest.collections.find((item) => item.name === token.collection)?.mode.name
      ) || null;
    const variable =
      index.variableById.get(token.figmaId) ||
      index.variableByQualifiedName.get(`${token.collection}::${token.name}`);
    if (!variable) {
      diffs.push(`${token.collection}/${token.name}: missing in Figma`);
      continue;
    }
    if (variable.id !== token.figmaId) {
      diffs.push(`${token.name}: variable id code=${token.figmaId} figma=${variable.id}`);
    }
    if (variable.resolvedType !== token.type) {
      diffs.push(`${token.name}: type code=${token.type} figma=${variable.resolvedType}`);
      continue;
    }
    if (!remoteMode) {
      continue;
    }
    const raw = variable.valuesByMode?.[remoteMode.modeId];
    if (raw === undefined) {
      diffs.push(`${token.name}: no value for Figma mode ${remoteMode.name}`);
      continue;
    }
    const remoteValue = normalizeRemoteValue(token, raw, index);
    if (JSON.stringify(remoteValue) !== JSON.stringify(token.value)) {
      diffs.push(`${token.name}: code=${JSON.stringify(token.value)} figma=${JSON.stringify(remoteValue)}`);
    }
    const expectedSyntax = `var(${token.cssVar})`;
    if (variable.codeSyntax?.WEB !== expectedSyntax) {
      diffs.push(`${token.name}: WEB codeSyntax=${JSON.stringify(variable.codeSyntax?.WEB)} expected=${expectedSyntax}`);
    }
  }

  if (diffs.length > 0) {
    process.stderr.write(`Figma/code drift detected:\n- ${diffs.join("\n- ")}\n`);
    process.exitCode = 2;
  } else {
    process.stdout.write("Figma/code token state is synchronized.\n");
  }
}

async function main() {
  const manifest = await loadManifest();

  if (command === "generate") {
    const cssPath = await writeGeneratedCss(manifest);
    process.stdout.write(`Generated ${cssPath}\n`);
    return;
  }

  if (command === "check") {
    const cssPath = resolve(frontendRoot, manifest.generatedCss);
    const actual = await readFile(cssPath, "utf8").catch(() => "");
    const expected = generateCss(manifest);
    if (actual !== expected) {
      process.stderr.write(
        "Generated AIIBP token CSS is stale. Run `npm run figma:generate` in frontend and commit the result.\n"
      );
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`Validated ${manifest.tokens.length} synchronized AIIBP tokens.\n`);
    return;
  }

  if (command === "pull") {
    await pull(manifest);
    process.stdout.write("Pulled Figma variables into the reviewable code token manifest.\n");
    return;
  }

  if (command === "push") {
    await push(manifest);
    process.stdout.write("Pushed the approved code token manifest to Figma variables.\n");
    return;
  }

  if (command === "remote-check") {
    await remoteCheck(manifest);
    return;
  }

  fail(`Unknown command "${command}". Expected generate, check, pull, push, or remote-check.`);
}

if (remoteCommands.has(command) && !process.env.FIGMA_ACCESS_TOKEN) {
  process.stderr.write(
    "Remote Figma synchronization requires FIGMA_ACCESS_TOKEN. Local generation/check remains available without it.\n"
  );
}

main().catch((error) => {
  process.stderr.write(`${error?.stack || error}\n`);
  process.exitCode = 1;
});
